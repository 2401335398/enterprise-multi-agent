import re


# ============================================================
# 强 Memory Signal
# ============================================================

MEMORY_KEYWORDS = [
    "以后",
    "后续",
    "从现在开始",
    "记住",
    "以后都",
    "统一",
    "固定",
    "默认",
    "重点关注",
    "重点看",
    "优先考虑",
    "改成",
    "改为",
    "调整为",
    "取消之前",
    "取消这个",
    "不再",
    "不要再",
    "长期",
    "一直",
]


# ============================================================
# 明显不值得进入 Semantic Memory 的消息
# ============================================================

SKIP_MESSAGES = {
    "好的",
    "好",
    "ok",
    "okay",
    "继续",
    "下一步",
    "可以",
    "明白了",
    "懂了",
    "谢谢",
    "收到",
    "行",
}


def should_process_memory(
    message: str
) -> bool:
    """
    判断当前用户消息是否值得进入
    Semantic Memory Pipeline。

    这是一个 deterministic fast path，
    目的是避免每个请求都调用 Memory Extractor LLM。
    """

    if not message:
        return False

    text = message.strip()

    if not text:
        return False

    lower_text = text.lower()

    # =========================================
    # 1. 极短、无意义消息直接跳过
    # =========================================

    if lower_text in SKIP_MESSAGES:
        return False

    # =========================================
    # 2. 太短的普通消息
    # =========================================

    if len(text) <= 4:
        return False

    # =========================================
    # 3. 明显长期约束/偏好/修改信号
    # =========================================

    if any(
        keyword in text
        for keyword in MEMORY_KEYWORDS
    ):
        return True

    # =========================================
    # 4. “我的偏好/习惯/目标”等表达
    # =========================================

    preference_patterns = [
        r"我(?:更|比较|通常|一直)?喜欢",
        r"我(?:更|比较|通常)?偏好",
        r"我的目标是",
        r"我的要求是",
        r"我的习惯是",
        r"这个项目.*要求",
        r"这个项目.*目标",
    ]

    if any(
        re.search(
            pattern,
            text
        )
        for pattern
        in preference_patterns
    ):
        return True

    # =========================================
    # 默认跳过
    # =========================================

    return False
